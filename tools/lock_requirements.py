"""Write requirements.lock: every pinned library with the checksums PyPI publishes."""
from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = """# Generated by tools/lock_requirements.py from requirements.txt. Do not edit.
# Install with: pip install --require-hashes -r requirements.lock
"""


def read_pins(path: Path) -> list[tuple[str, str]]:
    """Return (name, version) for each 'name==version' line, ignoring comments."""
    pins = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if "==" not in line:
            raise SystemExit(f"Every library must be pinned exactly (name==version): {line}")
        name, version = (part.strip() for part in line.split("==", 1))
        pins.append((name, version))
    return pins


def fetch_hashes(name: str, version: str) -> list[str]:
    """Ask PyPI for the sha256 of every file published for this exact version."""
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        data = json.load(response)
    files = data["urls"]
    if not files:
        raise SystemExit(f"{name} {version} has no files on PyPI")
    if any(f.get("yanked") for f in files):
        raise SystemExit(f"{name} {version} has been withdrawn (yanked) on PyPI")
    return sorted(f["digests"]["sha256"] for f in files)


def build_lock(pins: list[tuple[str, str]], fetch=fetch_hashes) -> str:
    """Return the lock file text for the given pins."""
    lines = [HEADER.rstrip("\n")]
    for name, version in pins:
        hashes = fetch(name, version)
        entry = [f"{name}=={version} \\"]
        entry += [f"    --hash=sha256:{h} \\" for h in hashes[:-1]]
        entry.append(f"    --hash=sha256:{hashes[-1]}")
        lines.append("\n".join(entry))
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requirements", default=str(ROOT / "requirements.txt"))
    parser.add_argument("--out", default=str(ROOT / "requirements.lock"))
    args = parser.parse_args(argv)
    text = build_lock(read_pins(Path(args.requirements)))
    Path(args.out).write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {Path(args.out).name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Write nguyen.toml: an invented fourth example household with years of weigh-ins, doses, feedings and prices."""
from __future__ import annotations

import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
SEED = 20261127  # the same file every time
DAYS = 4 * 365   # how far back the oldest records go


def q(text: str) -> str:
    return '"' + text.replace('"', '\\"') + '"'


def row(table: str, **values) -> str:
    lines = [f"[[{table}]]"]
    for key, value in values.items():
        if value is None:
            continue
        if isinstance(value, bool):
            lines.append(f"{key} = {'true' if value else 'false'}")
        elif isinstance(value, (int, float)):
            lines.append(f"{key} = {round(value, 2) if isinstance(value, float) else value}")
        elif isinstance(value, dict):
            inner = ", ".join(f"{k} = {q(v)}" for k, v in value.items())
            lines.append(f"{key} = {{ {inner} }}")
        elif isinstance(value, list):
            lines.append(f"{key} = [{', '.join(q(v) for v in value)}]")
        else:
            lines.append(f"{key} = {q(str(value))}")
    return "\n".join(lines) + "\n"


def ago(days: int, time: str | None = None) -> str:
    day = "today" if days == 0 else f"today-{days}"
    return f"{day}T{time}" if time else day


def build() -> str:
    rnd = random.Random(SEED)
    out = ['''# A made-up household for demos of charts, calendars and timelines (batch 23 item 125, Lane B draft).
# Every name, number and address is invented. Phone numbers use the Australian range set aside for fiction
# (0491 570 1xx); emails use example.com. Generated by make_demo.py with a fixed seed: edit that, not this.

title = "The Nguyen household"
summary = "Two adults, a teenager and a grandparent in a single-storey house in Victoria, Australia, with a dog and a cat, and four years of records."

[setup]
people = ["Linh Nguyen", "Sam Nguyen", "Ava Nguyen", "Bao Nguyen"]
pets = [{ name = "Biscuit", kind = "dog" }, { name = "Pepper", kind = "cat" }]
country = "Australia"
region = "Victoria"
home_type = "house"
storeys = 1
mobility_needs = true
hazards = ["bushfire", "heat", "storm"]
modules = ["home_care", "medicine_doses", "people", "pet_feeding", "pets", "routines", "stock", "vehicle_running", "vehicles"]
''']
    people = [
        dict(name="Linh Nguyen", phone="0491 570 110", relationship="partner", email="linh.nguyen@example.com"),
        dict(name="Sam Nguyen", phone="0491 570 111", relationship="partner", email="sam.nguyen@example.com"),
        dict(name="Ava Nguyen", relationship="child", birthday="2011-05-19"),
        dict(name="Bao Nguyen", phone="0491 570 112", relationship="parent",
             notes="Linh's father. Lives with us since 2023."),
        dict(name="Example Vet Clinic", phone="0491 570 113", relationship="professional"),
        dict(name="Example Mechanic", phone="0491 570 114", relationship="professional"),
    ]
    out.append("# ---- People ----\n")
    out += [row("people.people", **p) for p in people]
    out.append(row("people.roles", person="Example Vet Clinic", role="vet", priority=1))
    meds = ["Example tablet A 5 mg each morning", "Example eye drops, one drop each eye at night"]
    for detail in meds:
        out.append(row("people.important_info", person="Bao Nguyen", kind="medication", detail=detail))
    out.append(row("people.important_info", person="Bao Nguyen", kind="care_need",
                   detail="Walks with a stick; needs a hand on the back steps."))

    out.append("# ---- Pets: four years of weigh-ins, two years of feedings ----\n")
    out.append(row("pets.pets", name="Biscuit", species="dog", breed="Example cross", birthday="2018-02-10",
                   owner="Sam Nguyen", vet="Example Vet Clinic", vaccinations_due="today+40"))
    out.append(row("pets.pets", name="Pepper", species="cat", birthday="2020-08-01", owner="Ava Nguyen",
                   vet="Example Vet Clinic", vaccinations_due="today+120"))
    # Biscuit: gains slowly for two and a half years, then a vet-advised diet brings the weight down.
    weight = 24.0
    for day in range(DAYS, -1, -30):
        trend = 0.12 if day > 540 else -0.18
        weight = max(19.0, weight + trend + rnd.uniform(-0.25, 0.25))
        out.append(row("pets.weigh_ins", pet="Biscuit", day=ago(day), weight=round(weight, 1),
                       notes="Vet says: smaller portions and no table scraps." if day == 540 else None))
    cat = 4.2
    for day in range(DAYS, -1, -90):
        cat = cat + rnd.uniform(-0.15, 0.15)
        out.append(row("pets.weigh_ins", pet="Pepper", day=ago(day), weight=round(cat, 1)))
    out.append(row("pets.vet_visits", pet="Biscuit", day=ago(540), vet="Example Vet Clinic",
                   reason="Weight check: diet advised"))
    out.append(row("pets.vet_visits", pet="Biscuit", day=ago(180), vet="Example Vet Clinic",
                   reason="Annual check and vaccination"))
    for day in range(730, -1, -1):
        portion = 260 if day > 540 else 210  # put out, not eaten: the diet shows as smaller portions
        for time in ("07:15", "18:00"):
            if rnd.random() < 0.06:
                continue  # some feedings were never written down: a gap is not a missed meal
            out.append(row("pet_feeding.servings", pet="Biscuit", given_at=ago(day, time), kind="bowl",
                           bowl="Laundry bowl", food="Example dry dog food", amount=portion, unit="g"))
        if rnd.random() < 0.85:
            out.append(row("pet_feeding.servings", pet="Pepper", given_at=ago(day, "07:30"), kind="bowl",
                           bowl="Kitchen bowl", food="Example cat pouch", amount=1, unit="pouch"))

    out.append("# ---- Medicine doses: one year, two medicines ----\n")
    for day in range(365, -1, -1):
        for detail, time in ((meds[0], "08:00"), (meds[1], "21:00")):
            if rnd.random() < 0.05:
                continue
            out.append(row("medicine_doses.doses", recipient="Bao Nguyen",
                           medication={"person": "Bao Nguyen", "kind": "medication", "detail": detail},
                           given_at=ago(day, time), given_by=rnd.choice(["Linh Nguyen", "Sam Nguyen"])))

    out.append("# ---- Routines: three years of bins and plants ----\n")
    out.append(row("routines.routines", name="Put the bins out", who="Sam Nguyen", repeat_count=1,
                   repeat_unit="weeks", first_due=ago(3 * 365), next_due="today+3", last_done=ago(4)))
    out.append(row("routines.routines", name="Water the vegetable patch", who="Ava Nguyen", repeat_count=2,
                   repeat_unit="days", first_due=ago(2 * 365), next_due="today+1", last_done=ago(1)))
    for day in range(3 * 365, 3, -7):
        outcome = "skipped" if rnd.random() < 0.04 else "done"
        out.append(row("routines.times", routine="Put the bins out", outcome=outcome, planned_for=ago(day),
                       done_on=ago(day), done_by="Sam Nguyen" if outcome == "done" else None))
    for day in range(2 * 365, 0, -2):
        if rnd.random() < 0.15:
            continue
        out.append(row("routines.times", routine="Water the vegetable patch", outcome="done", planned_for=ago(day),
                       done_on=ago(day), done_by="Ava Nguyen"))

    out.append("# ---- Vehicles: four years of readings and services ----\n")
    out.append(row("vehicles.vehicles", name="Family wagon", registration_due="today+75"))
    out.append(row("vehicles.services", vehicle="Family wagon", name="Logbook service", last_done=ago(160),
                   next_due="today+20"))
    odometer = 61000
    for day in range(DAYS, -1, -30):
        odometer += rnd.randint(800, 1500)
        out.append(row("vehicle_running.readings", vehicle="Family wagon", read_at=ago(day, "09:00"),
                       distance=odometer, unit="km"))

    out.append("# ---- Home care: five years of work done ----\n")
    out.append(row("home_care.jobs", name="Clean the gutters", kind="gutters", last_done=ago(120), next_due="today+60"))
    out.append(row("home_care.jobs", name="Service the air conditioner", kind="other", last_done=ago(300),
                   next_due="today+65"))
    for day in range(5 * 365, 100, -180):
        out.append(row("home_care.work_done", job="Clean the gutters", done_on=ago(day), done_by="Sam Nguyen"))
    for day in range(5 * 365, 299, -365):
        out.append(row("home_care.work_done", job="Service the air conditioner", done_on=ago(day)))

    out.append("# ---- Household stock: two years of priced shopping ----\n")
    out.append(row("stock.places", name="Kitchen", floor="street"))
    out.append(row("stock.places", name="Pantry", inside="Kitchen"))
    out.append(row("stock.places", name="Laundry", floor="street"))
    items = [("Example dry dog food (8 kg bag)", "pet", "bags", 1, "Laundry", 54.00, 42),
             ("Example cat pouches (12 pack)", "pet", "packs", 2, "Laundry", 13.50, 14),
             ("Rice (5 kg)", "pantry", "bags", 1, "Pantry", 11.00, 60),
             ("Tinned tomatoes", "pantry", "tins", 6, "Pantry", 1.20, 14),
             ("Bottled water (10 L)", "water", "litres", 20, "Laundry", 4.50, 90)]
    for name, category, unit, minimum, place, _price, _every in items:
        on_hand = 20 if unit == "litres" else (8 if unit == "tins" else 1)  # what is on hand today
        out.append(row("stock.items", name=name, category=category, quantity=on_hand, unit=unit, minimum=minimum,
                       place=place, drinking=True if category == "water" else None))
    for name, _category, unit, _minimum, _place, price, every in items:
        for day in range(730, 0, -every):
            amount = 10 if unit == "litres" else (4 if unit == "tins" else 1)
            each = round(price * (1 + (730 - day) / 730 * 0.08), 2)  # prices creep up about 8% over two years
            out.append(row("stock.movements", item=name, reason="bought", amount=amount, happened_on=ago(day),
                           price=each, price_basis="each" if amount > 1 else "total"))
            out.append(row("stock.movements", item=name, reason="used", amount=amount, happened_on=ago(max(day - every + 2, 1))))
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    (HERE / "nguyen.toml").write_text(text, encoding="utf-8")
    print(f"Wrote nguyen.toml: {text.count('[[')} records.")
